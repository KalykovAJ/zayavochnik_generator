def _deep_merge(base: dict, override: dict) -> dict:
    """Рекурсивно объединяет два словаря: override имеет приоритет над base."""
    result = copy.deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = _deep_merge(result[key], value)
        else:
            result[key] = value
    return result


def build_excel_styles(network_overrides: dict) -> dict:
    """
    Собирает итоговый EXCEL_STYLES для конкретной сети АЗС: берёт
    COMMON_EXCEL_STYLES и докладывает/перекрывает его уникальными для
    сети значениями из network_overrides.
    """
    return _deep_merge(COMMON_EXCEL_STYLES, network_overrides)
